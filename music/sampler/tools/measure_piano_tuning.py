"""Measure the Salamander piano's actual string tuning (f0 and inharmonicity B per key)
and write sampler/_piano_tuning.py, used by the pedal sympathetic-resonance model.

    python music/sampler/tools/measure_piano_tuning.py      （要整套 Salamander：fetch_samples.py --only piano）

For every key 21..108 and both keyswitched tunings, one note (velocity 70, no release /
pedal noise) is rendered through sampler.piano; partials n = 1..8 below 10 kHz are located
(peak within +-70 cents of n * f_ET * sqrt(1 + B0 n^2), parabolic interpolation on a
Hann-windowed, 2^20-point FFT of 0.15..1.9 s) and f_n = n f0 sqrt(1 + B n^2) is fitted by
least squares on (f_n / n)^2 = f0^2 + f0^2 B n^2. Deterministic.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sampler._dsp import SR  # noqa: E402
from sampler.piano import render_piano  # noqa: E402


def measure(key, tuning):
    y = render_piano([(0.0, 2.0, key, 70)], string_res=0, hammer_noise=0, pedal_noise=0,
                     tuning=tuning, duration=2.0, sympathetic=0.0)
    m = y.mean(axis=1).astype(np.float64)[int(0.15 * SR):int(1.9 * SR)]
    m = m * np.hanning(len(m))
    nfft = 1 << 20
    S = np.abs(np.fft.rfft(m, nfft))
    f = np.fft.rfftfreq(nfft, 1 / SR)
    top = S.max()
    f_et = 440.0 * 2 ** ((key - 69) / 12)
    b0 = 10 ** (-3.6 + 0.022 * max(0, key - 50))
    pts = []
    for n in range(1, 9):
        fe = n * f_et * np.sqrt(1 + b0 * n * n)
        if fe > 10000:
            break
        lo, hi = fe * 2 ** (-70 / 1200), fe * 2 ** (70 / 1200)
        w = np.flatnonzero((f >= lo) & (f <= hi))
        j = w[np.argmax(S[w])]
        if S[j] < top * 10 ** (-55 / 20) or j in (w[0], w[-1]):
            continue
        a, b, c = np.log(S[j - 1]), np.log(S[j]), np.log(S[j + 1])
        fj = f[j] + 0.5 * (a - c) / (a - 2 * b + c) * (f[1] - f[0])
        pts.append((n, fj))
    if not pts:
        return 0.0, b0, ()
    n = np.array([p[0] for p in pts], dtype=float)
    fn = np.array([p[1] for p in pts])
    if len(pts) >= 3:
        slope, icpt = np.polyfit(n * n, (fn / n) ** 2, 1)
        f0 = np.sqrt(max(icpt, 1e-6))
        B = float(np.clip(slope / icpt, 0.0, 0.05))
    else:
        B = b0
        f0 = float(np.median(fn / (n * np.sqrt(1 + B * n * n))))
    return (float(1200 * np.log2(f0 / f_et)), B,
            tuple((int(a), round(float(b), 3)) for a, b in pts))


def main():
    lines = ['"""Measured tuning of the Salamander piano (generated by tools/measure_piano_tuning.py;',
             'do not edit). key -> (cents of the fitted f0 from 12-TET A4=440, inharmonicity B,',
             '((partial number, measured Hz), ...))."""', '']
    for tuning in ('natural', 'retuned'):
        rows = {}
        for key in range(21, 109):
            c, B, k = measure(key, tuning)
            rows[key] = (round(c, 2), float(f'{B:.3e}'), k)
            print(tuning, key, rows[key], flush=True)
        lines.append(f'{tuning.upper()} = {{')
        for key, v in rows.items():
            lines.append(f'    {key}: {v},')
        lines.append('}')
        lines.append('')
    (ROOT / 'sampler' / '_piano_tuning.py').write_text('\n'.join(lines))
    print('wrote sampler/_piano_tuning.py')


if __name__ == '__main__':
    main()
